"""
CalculiX / Abaqus `.inp` and Gmsh `.msh` interoperability.

Export writes a complete, CalculiX-compatible deck from a project (one `*ELSET`, `*MATERIAL` and `*SOLID SECTION`
per part) so a model can be cross-checked in any Abaqus-style solver. Import reads nodes and elements (C3D4, C3D10, C3D8,
C3D20 incl. reduced variants), element blocks as parts, and `*MATERIAL` / `*SOLID SECTION` cards. The engine itself
never calls an external solver.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

from .elements import ELEMENT_TYPES
from .materials import Material
from .model import FEMesh

# CalculiX face numbering (S1..S6 / S1..S4) expressed as sets of CORNER node indices (0-based, local)
_CCX_FACES = {
    "C3D4": [(0, 1, 2), (0, 3, 1), (1, 3, 2), (2, 3, 0)],
    "C3D10": [(0, 1, 2), (0, 3, 1), (1, 3, 2), (2, 3, 0)],
    "C3D8": [(0, 1, 2, 3), (4, 7, 6, 5), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)],
    "C3D20": [(0, 1, 2, 3), (4, 7, 6, 5), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)],
}


class InpError(ValueError):
    pass


def _safe(text: Any) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", str(text))[:30] or "X"


# ------------------------------------------------------------------- export
def _ccx_face(mesh: FEMesh, elem: int, face_corner_nodes) -> int:
    corners = set(int(x) for x in face_corner_nodes)
    conn = mesh.elems[elem]
    for k, loc in enumerate(_CCX_FACES[mesh.et.name], start=1):
        if {int(conn[i]) for i in loc} == corners:
            return k
    raise InpError("Could not map a face to the CalculiX face numbering")


def _material_card(w, name: str, mat: Material) -> None:
    w(f"*MATERIAL, NAME={name}")
    w("*ELASTIC")
    w(f"{mat.E:.10g}, {mat.nu:.10g}")
    w("*DENSITY")
    w(f"{mat.density:.10g}")
    if mat.alpha:
        w("*EXPANSION")
        w(f"{mat.alpha:.10g}")
    w("*CONDUCTIVITY")
    w(f"{mat.conductivity:.10g}")
    w("*SPECIFIC HEAT")
    w(f"{mat.specific_heat:.10g}")
    if mat.plastic:
        w("*PLASTIC")
        w(f"{mat.yield_stress:.10g}, 0.")
        w(f"{mat.yield_stress + mat.hardening * 1.0:.10g}, 1.")


def export_inp(project: Dict[str, Any]) -> str:
    """Return the .inp text for a project dict (same structure the API stores)."""
    from .runner import Model  # local import: runner imports this package

    model = Model(project)
    mesh, st = model.mesh, model.settings
    kind = model.analysis
    L: List[str] = []
    w = L.append
    w("** Generated by Gearhead FEA for interoperability (CalculiX / Abaqus syntax)")
    w(f"** Project: {project.get('name', '')}")
    w("*NODE, NSET=NALL")
    for i, (x, y, z) in enumerate(mesh.nodes, start=1):
        w(f"{i}, {x:.10g}, {y:.10g}, {z:.10g}")
    w(f"*ELEMENT, TYPE={mesh.et.name}, ELSET=EALL")
    for i, conn in enumerate(mesh.elems, start=1):
        ids = [str(int(c) + 1) for c in conn]
        w(f"{i}, " + ", ".join(ids[:15]))
        rest = ids[15:]
        while rest:
            w(", ".join(rest[:16]))
            rest = rest[16:]

    # parts -> element sets; library materials -> *MATERIAL; one *SOLID SECTION per part
    names = {"default": (project.get("material") or {}).get("name") or "Material"}
    for m in project.get("materials") or []:
        names[str(m["id"])] = m.get("name") or str(m["id"])
    elset_of, mat_name = {}, {}
    for k, part in enumerate(model.parts):
        elset = f"PART{k + 1}_{_safe(part.get('name', part['id']))}"
        elset_of[part["id"]] = elset
        w(f"*ELSET, ELSET={elset}, GENERATE")
        w(f"{part['elem_start'] + 1}, {part['elem_end']}, 1")
    for part in model.parts:
        mid = str(part.get("material_id") or "default")
        if mid not in mat_name:
            mat_name[mid] = f"MAT{len(mat_name) + 1}_{_safe(names.get(mid, mid))}"
            _material_card(w, mat_name[mid], model.materials[mid])
    for part in model.parts:
        w(f"*SOLID SECTION, ELSET={elset_of[part['id']]}, MATERIAL={mat_name[str(part.get('material_id') or 'default')]}")

    thermal_only = kind in ("thermal", "thermal_transient")
    # boundary conditions
    mech_bc, temp_bc = [], []
    for bc in model.bcs:
        is_t = model._is_temperature_bc(bc)
        for nid in bc.get("node_ids", []):
            if is_t:
                temp_bc.append(f"{int(nid) + 1}, 11, 11, {float((bc.get('values') or [0])[0]):.10g}")
            else:
                dofs = bc.get("dofs") or []
                vals = bc.get("values") or [0.0] * len(dofs)
                for d, v in zip(dofs, vals):
                    mech_bc.append(f"{int(nid) + 1}, {int(d) + 1}, {int(d) + 1}, {float(v):.10g}")
    if model.refs or model.cons_raw:
        w("** NOTE: reference points, rigid-body and tie constraints are not written to this deck.")
    w("*STEP" + (", NLGEOM=NO" if kind == "nonlinear" else ""))
    if kind in ("static", "nonlinear"):
        w("*STATIC")
    elif kind == "modal":
        w("*FREQUENCY")
        w(str(int(st.get("n_modes") or project.get("n_modes") or 6)))
    elif kind == "buckling":
        w("*STATIC")
    elif kind == "dynamic":
        w("*DYNAMIC")
        t_end, n = float(st.get("t_end", 0.1)), int(st.get("n_steps", 200))
        w(f"{t_end / n:.8g}, {t_end:.8g}")
    elif kind == "thermal":
        w("*HEAT TRANSFER, STEADY STATE")
    elif kind == "thermal_transient":
        w("*HEAT TRANSFER")
        t_end, n = float(st.get("t_end", 100.0)), int(st.get("n_steps", 100))
        w(f"{t_end / n:.8g}, {t_end:.8g}")
    elif kind == "thermomech":
        w("*UNCOUPLED TEMPERATURE-DISPLACEMENT, STEADY STATE")
    if kind == "dynamic" and (st.get("rayleigh_alpha") or st.get("rayleigh_beta")):
        w(f"** Rayleigh damping alpha={st.get('rayleigh_alpha', 0)} beta={st.get('rayleigh_beta', 0)}")
    if mech_bc or temp_bc:
        w("*BOUNDARY")
        L.extend(mech_bc + temp_bc)
    for ld in model.loads:
        k = ld.get("load_type", "force")
        if k == "force" and ld.get("node_ids"):
            share = np.array(ld.get("vector", [0, 0, 0]), dtype=float) / len(ld["node_ids"])
            w("*CLOAD")
            for nid in ld["node_ids"]:
                for d in range(3):
                    if share[d] != 0:
                        w(f"{int(nid) + 1}, {d + 1}, {share[d]:.10g}")
        elif k in ("pressure", "surface_flux", "convection", "radiation") and ld.get("faces"):
            b = mesh.boundary()
            idx = b.faces_for_triangles(ld["faces"])
            nc = 3 if b.face_type.startswith("tri") else 4
            tag = {"pressure": "*DLOAD", "surface_flux": "*DFLUX", "convection": "*FILM", "radiation": "*RADIATE"}[k]
            w(tag)
            for fi in idx:
                e = int(b.elem[fi])
                s = _ccx_face(mesh, e, b.face_nodes[fi][:nc])
                if k == "pressure":
                    w(f"{e + 1}, P{s}, {float(ld.get('magnitude') or 0):.10g}")
                elif k == "surface_flux":
                    w(f"{e + 1}, S{s}, {float(ld.get('magnitude') or 0):.10g}")
                elif k == "convection":
                    w(f"{e + 1}, F{s}, {float(ld.get('T_inf') or 0):.10g}, {float(ld.get('h') or 0):.10g}")
                else:
                    w(f"{e + 1}, R{s}, {float(ld.get('T_inf') or 0):.10g}, {float(ld.get('emissivity', 0.8)):.10g}")
        elif k == "heat_flux" and ld.get("node_ids"):
            w("*CFLUX")
            for nid in ld["node_ids"]:
                w(f"{int(nid) + 1}, 11, {float(ld.get('magnitude') or 0) / len(ld['node_ids']):.10g}")
    g = project.get("gravity") or {}
    if g.get("enabled"):
        vec = np.array([g.get("x", 0), g.get("y", 0), g.get("z", -9.81)], dtype=float)
        mag = float(np.linalg.norm(vec))
        if mag > 0:
            d = vec / mag
            w("*DLOAD")
            w(f"EALL, GRAV, {mag:.10g}, {d[0]:.10g}, {d[1]:.10g}, {d[2]:.10g}")
    if not thermal_only:
        w("*NODE FILE")
        w("U")
        w("*EL FILE")
        w("S, E")
    else:
        w("*NODE FILE")
        w("NT")
    w("*END STEP")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------- import
_TYPE_MAP = {
    "C3D4": "C3D4", "C3D10": "C3D10", "C3D8": "C3D8", "C3D8R": "C3D8", "C3D8I": "C3D8",
    "C3D20": "C3D20", "C3D20R": "C3D20", "C3D10M": "C3D10",
}


@dataclass
class InpModel:
    mesh: FEMesh
    parts: List[Dict[str, Any]] = field(default_factory=list)       # {name, elem_start, elem_end, material (name or None)}
    materials: Dict[str, Dict[str, float]] = field(default_factory=dict)  # name -> property dict


def _plastic_from_rows(rows: List[Tuple[float, float]]) -> Tuple[float, float]:
    """(yield stress, linear hardening modulus) from *PLASTIC rows of (stress, plastic strain)."""
    if not rows:
        return 0.0, 0.0
    sy = rows[0][0]
    if len(rows) >= 2 and rows[-1][1] > rows[0][1]:
        return sy, max((rows[-1][0] - rows[0][0]) / (rows[-1][1] - rows[0][1]), 0.0)
    return sy, 0.0


def import_inp_model(text: str) -> InpModel:
    """Parse nodes, elements (continuation lines supported), element-set parts, materials and solid sections."""
    lines = [ln.strip() for ln in text.splitlines()]
    node_ids: List[int] = []
    coords: List[List[float]] = []
    elems: List[Tuple[int, List[int]]] = []
    blocks: List[Tuple[str, int]] = []        # (elset name, index of first element)
    etype = None
    mode = None
    card = None
    cur_mat: Optional[str] = None
    materials: Dict[str, Dict[str, Any]] = {}
    plastic_rows: Dict[str, List[Tuple[float, float]]] = {}
    sections: Dict[str, str] = {}             # elset -> material name
    elsets: Dict[str, List[int]] = {}         # explicit *ELSET definitions (file element ids)
    cur_elset: Optional[str] = None
    elset_generate = False
    pending: List[int] = []
    pend_id = None
    pend_need = 0
    for ln in lines:
        if not ln or ln.startswith("**"):
            continue
        if ln.startswith("*"):
            head = ln.upper()
            mode = card = None
            if head.startswith("*NODE") and not head.startswith("*NODE FILE") and not head.startswith("*NODE PRINT"):
                mode = "node"
            elif head.startswith("*ELEMENT") and not head.startswith("*ELEMENT OUTPUT"):
                m = re.search(r"TYPE\s*=\s*([A-Z0-9]+)", head)
                if not m:
                    raise InpError("*ELEMENT block without TYPE=")
                raw = m.group(1)
                if raw not in _TYPE_MAP:
                    raise InpError(f"Element type {raw} is not supported (supported: C3D4, C3D10, C3D8, C3D20)")
                if etype and etype != _TYPE_MAP[raw]:
                    raise InpError("Models mixing different element types are not supported")
                etype = _TYPE_MAP[raw]
                es = re.search(r"ELSET\s*=\s*([^,\s]+)", ln, re.I)
                blocks.append((es.group(1) if es else "EALL", len(elems)))
                mode = "elem"
            elif head.startswith("*ELSET"):
                es = re.search(r"ELSET\s*=\s*([^,\s]+)", ln, re.I)
                if es:
                    cur_elset = es.group(1)
                    elset_generate = "GENERATE" in head
                    elsets.setdefault(cur_elset, [])
                    mode = "elset"
            elif head.startswith("*MATERIAL"):
                nm = re.search(r"NAME\s*=\s*([^,\s]+)", ln, re.I)
                cur_mat = nm.group(1) if nm else f"Material{len(materials) + 1}"
                materials[cur_mat] = {}
                plastic_rows[cur_mat] = []
                mode = "mat"
            elif head.startswith("*SOLID SECTION"):
                es = re.search(r"ELSET\s*=\s*([^,\s]+)", ln, re.I)
                mt = re.search(r"MATERIAL\s*=\s*([^,\s]+)", ln, re.I)
                if es and mt:
                    sections[es.group(1)] = mt.group(1)
            elif mode is None and cur_mat and head.split(",")[0] in (
                    "*ELASTIC", "*DENSITY", "*EXPANSION", "*CONDUCTIVITY", "*SPECIFIC HEAT", "*PLASTIC"):
                mode = "mat"
            if head.split(",")[0] in ("*ELASTIC", "*DENSITY", "*EXPANSION", "*CONDUCTIVITY", "*SPECIFIC HEAT", "*PLASTIC"):
                card = head.split(",")[0]
                mode = "mat"
            continue
        parts = [p for p in (x.strip() for x in ln.split(",")) if p != ""]
        if mode == "node":
            if len(parts) < 4:
                raise InpError(f"Bad node line: {ln}")
            node_ids.append(int(parts[0]))
            coords.append([float(parts[1]), float(parts[2]), float(parts[3])])
        elif mode == "elem":
            need = ELEMENT_TYPES[etype].n_nodes
            if pend_id is None:
                pend_id, pending, pend_need = int(parts[0]), [int(p) for p in parts[1:]], need
            else:
                pending += [int(p) for p in parts]
            if len(pending) >= pend_need:
                elems.append((pend_id, pending[:pend_need]))
                pend_id, pending = None, []
        elif mode == "elset" and cur_elset:
            try:
                nums = [int(float(p)) for p in parts]
            except ValueError:
                continue
            if elset_generate and len(nums) >= 2:
                step = nums[2] if len(nums) > 2 and nums[2] else 1
                elsets[cur_elset].extend(range(nums[0], nums[1] + 1, step))
            else:
                elsets[cur_elset].extend(nums)
        elif mode == "mat" and cur_mat and card:
            try:
                nums = [float(p) for p in parts]
            except ValueError:
                continue
            md = materials[cur_mat]
            if card == "*ELASTIC" and len(nums) >= 2:
                md["E"], md["nu"] = nums[0], nums[1]
            elif card == "*DENSITY" and nums:
                md["density"] = nums[0]
            elif card == "*EXPANSION" and nums:
                md["alpha"] = nums[0]
            elif card == "*CONDUCTIVITY" and nums:
                md["conductivity"] = nums[0]
            elif card == "*SPECIFIC HEAT" and nums:
                md["specific_heat"] = nums[0]
            elif card == "*PLASTIC" and len(nums) >= 2:
                plastic_rows[cur_mat].append((nums[0], nums[1]))
    if not node_ids or not elems:
        raise InpError("No nodes or elements found in the file")
    for name, rows in plastic_rows.items():
        if rows:
            materials[name]["yield_stress"], materials[name]["hardening"] = _plastic_from_rows(rows)
    remap = {nid: i for i, nid in enumerate(node_ids)}
    try:
        conn = np.array([[remap[n] for n in e] for _, e in elems], dtype=np.int64)
    except KeyError as exc:
        raise InpError(f"An element references missing node {exc.args[0]}") from exc
    mesh = FEMesh(np.array(coords), conn, etype)
    mesh.ensure_positive_orientation()

    # parts from the element sets named in *SOLID SECTION when they tile the mesh with contiguous ranges
    eid_index = {eid: i for i, (eid, _) in enumerate(elems)}
    named: List[Dict[str, Any]] = []
    for name, mat_name in sections.items():
        idx = sorted(eid_index[e] for e in elsets.get(name, []) if e in eid_index)
        if idx and idx[-1] - idx[0] + 1 == len(idx):
            named.append({"name": name, "elem_start": idx[0], "elem_end": idx[-1] + 1, "material": mat_name})
    named.sort(key=lambda q: q["elem_start"])
    edge = 0
    tiles = bool(named)
    for q in named:
        tiles = tiles and q["elem_start"] == edge
        edge = q["elem_end"]
    if tiles and edge == len(elems) and len(named) > 1:
        return InpModel(mesh, named, {k: v for k, v in materials.items() if v})

    # otherwise element blocks -> parts (consecutive blocks with the same ELSET merge)
    parts_out: List[Dict[str, Any]] = []
    for i, (name, start) in enumerate(blocks):
        end = blocks[i + 1][1] if i + 1 < len(blocks) else len(elems)
        if end <= start:
            continue
        if parts_out and parts_out[-1]["name"] == name:
            parts_out[-1]["elem_end"] = end
            continue
        parts_out.append({"name": name, "elem_start": start, "elem_end": end, "material": sections.get(name)})
    return InpModel(mesh, parts_out, {k: v for k, v in materials.items() if v})


def import_inp(text: str) -> FEMesh:
    """Mesh only (see import_inp_model for parts and materials)."""
    return import_inp_model(text).mesh


def import_msh(text: str) -> FEMesh:
    """Gmsh ASCII format 2.2: tetrahedra (type 4, 11) and hexahedra (type 5)."""
    sec = {}
    cur, buf = None, []
    for ln in text.splitlines():
        ln = ln.strip()
        if ln.startswith("$End"):
            sec[cur] = buf
            cur, buf = None, []
        elif ln.startswith("$"):
            cur, buf = ln[1:], []
        elif cur:
            buf.append(ln)
    if "Nodes" not in sec or "Elements" not in sec:
        raise InpError("Not a Gmsh ASCII .msh file (expected $Nodes and $Elements; format 2.2)")
    fmt = (sec.get("MeshFormat") or ["2.2"])[0].split()[0]
    if not fmt.startswith("2"):
        raise InpError(f"Gmsh format {fmt} is not supported; export as ASCII version 2.2")
    nl = sec["Nodes"]
    n = int(nl[0])
    ids, pts = [], []
    for ln in nl[1:1 + n]:
        p = ln.split()
        ids.append(int(p[0]))
        pts.append([float(p[1]), float(p[2]), float(p[3])])
    remap = {nid: i for i, nid in enumerate(ids)}
    by_type: Dict[int, List[List[int]]] = {}
    for ln in sec["Elements"][1:]:
        p = [int(x) for x in ln.split()]
        etype, ntags = p[1], p[2]
        by_type.setdefault(etype, []).append([remap[x] for x in p[3 + ntags:]])
    solids = {k: v for k, v in by_type.items() if k in (4, 11, 5)}
    if len(solids) != 1:
        raise InpError("The mesh must contain exactly one solid element type (tetra4, tetra10 or hexa8)")
    (gtype, rows), = solids.items()
    arr = np.array(rows, dtype=np.int64)
    if gtype == 11:
        arr = arr[:, [0, 1, 2, 3, 4, 5, 6, 7, 9, 8]]  # gmsh edge order -> Abaqus order
    name = {4: "C3D4", 11: "C3D10", 5: "C3D8"}[gtype]
    mesh = FEMesh(np.array(pts), arr, name)
    mesh.ensure_positive_orientation()
    return mesh
